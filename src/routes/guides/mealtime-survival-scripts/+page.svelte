    <h1>Mealtime Survival Scripts — What to Say (and Not Say) at the Table</h1>
    <div class="article-body">

      <p class="lede">You know what does not work: begging, bribing, threatening, counting down, reciting the nutritional content of a single pea. But when you are tired and the child is refusing and the broccoli is getting cold, it is hard to find the right words. These scripts give you something to say instead.</p>

      <div class="disclaimer-box"><strong>This is information, not therapy.</strong> If mealtimes are causing genuine distress every day, the issue may be bigger than what you say at the table. A GP, health visitor or paediatric dietitian can help.</div>

      <h2>Before the meal: setting up success</h2>

      <p>The script starts before anyone sits down. A predictable mealtime structure reduces anxiety for fussy eaters, most of whom rely on knowing what is coming. These phrases help set the frame without creating a negotiation.</p>

      <h3>The preview script</h3>
      <p>Tell the child what is for dinner 10–15 minutes before serving. Keep it factual and short. Do not ask for a reaction or pre-approval.</p>
      <p><em>"Dinner is in ten minutes. We are having pasta with tomato sauce, green beans and garlic bread. The garlic bread is ready. The beans are on the table."</em></p>
      <p>No "Is that okay?" No "You like garlic bread, right?" Just information. The child processes without pressure.</p>

      <h3>The involvement script</h3>
      <p>If the child can help with a low-risk task, they feel more control without needing to control the meal itself.</p>
      <p><em>"Can you put the napkins on the table? I need someone to carry the water jug."</em></p>
      <p>Do not ask them to help with the food itself unless they volunteer. A child who is anxious about the meal will not relax by being asked to stir it.</p>

      <h2>During the meal: the hard moments</h2>

      <p>This is where most scripts fall apart because the parent is trying to get the child to eat, and the child is trying to get the parent to stop. The goal here is not to make the child eat. The goal is to preserve a calm table so the child can learn, over time, that food is not a fight.</p>

      <h3>When they say "I don't like it" before tasting it</h3>
      <p>Do not argue. Do not counter with "You liked it last week." The child is expressing anxiety, not an opinion about the food.</p>
      <p>Say: <em>"That's fine. You don't have to eat it. It is staying here on the table."</em></p>
      <p>This is not giving in. It is accepting their experience while keeping the food available. The same food might be eaten next time, or in five minutes when the anxiety passes.</p>

      <h3>When they ask for something else</h3>
      <p>If a safe food is already on the table, redirect to it. If not, hold the boundary without punishing.</p>
      <p>Say: <em>"This is what's for dinner tonight. You can eat any part of it you want. There will be breakfast tomorrow."</em></p>
      <p>No bargaining ("eat one bite and I'll get you a yoghurt"). No shaming ("you can't just eat bread"). The meal is what it is. The choice to eat or not belongs to the child.</p>

      <h3>When they are pushing food around but not eating</h3>
      <p>This is often a compromise — the child is staying at the table (which is good) but not yet ready to eat. Do not fill the silence with encouragement.</p>
      <p>Say nothing. Or redirect to conversation: <em>"I saw a wood pigeon on the fence today, it had one leg."</em></p>
      <p>The less attention on the plate, the more likely the child will eventually eat. They might not eat tonight. But they will notice that the table was somewhere they could sit without being watched.</p>

      <h3>When they gag</h3>
      <p>A gag reflex when a non-preferred food touches the mouth is not naughtiness. It is a physical response. Do not punish or make a fuss. Remove the food calmly.</p>
      <p>Say: <em>"That food did not work for you. Here is your water. We can try it another time."</em></p>
      <p>If gagging happens frequently, speak to your GP. Frequent gagging on non-preferred textures can indicate a sensory difficulty or oral motor issue that needs professional assessment.</p>

      <h2>After the meal: closing the loop</h2>

      <p>How you end the meal matters as much as how you begin it. The goal is to finish on a note that lets everyone leave the table without carrying the meal's tension with them.</p>

      <h3>The separation script</h3>
      <p>When a child has eaten very little, the temptation is to ask them to stay longer or try again. Do not. It teaches them that the meal only ends when they have eaten enough, which gives them control over exactly the thing you want them to stop controlling.</p>
      <p>Say: <em>"Dinner is over. You can leave the table now. See you for breakfast."</em></p>
      <p>The same timer for everyone. No staying for extra bites. The child learns that the meal is finite and safe, not a hostage situation.</p>

      <h3>The post-mortem ban</h3>
      <p>Do not discuss what the child ate or did not eat once the meal is over. Not with your partner in the kitchen. Not on the phone to your mum. The child will pick up that their eating is being tracked and discussed, which adds pressure to the next meal.</p>
      <p>If you need to debrief, do it out of earshot. Better still, wait until the next day and ask yourself: was the table calm? That is the only measure that matters right now.</p>

      <h2>Scripts for when you are about to lose your temper</h2>

      <p>Every parent reaches this point. The child has refused everything for the third night running. You have cooked, you are tired, and you can feel yourself about to say something you will regret.</p>

      <p>Say this to yourself: <em>"I am the adult. The food is here. The pressure is off. I do not need to make them eat tonight."</em></p>

      <p>If you need to leave the table, leave. Say: <em>"I need a minute. I am going to the kitchen. Your plate will still be here when I come back."</em></p>

      <p>You are not failing. You are parenting a child who is hard to feed, and you are doing it without making them feel worse. That is not small.</p>

