    <h1>Fussy Eating or ARFID — How to Tell the Difference</h1>
    <div class="article-body">

<p>Most toddlers and preschoolers go through a picky phase. It is normal, frustrating, and usually temporary. But there is a line where ordinary fussy eating becomes something that needs a different kind of response. ARFID (Avoidant/Restrictive Food Intake Disorder) is a recognised eating disorder that looks like extreme picky eating but behaves differently — and needs different support.</p>

<div class="disclaimer-box"><strong>This is information, not a diagnosis.</strong> If you are concerned about your child's eating, speak to your GP or health visitor. ARFID is a clinical diagnosis, not something a website can give you.</div>

<h2 id="normal-fussy-eating">What normal fussy eating looks like</h2>
<p>Ordinary fussy eating tends to follow a predictable pattern. The child eats a reasonable range of foods, then narrows it. They might reject vegetables, refuse anything mixed together, or eat only beige foods for weeks. But they still eat. They still grow. They still have energy. The phase usually passes with patience, exposure and time.</p>
<p>Key signs: the child eats enough to maintain weight, they accept some foods from most food groups, they can be persuaded (eventually) to try something new, and the pickiness fluctuates — good weeks and bad weeks.</p>

<h2 id="red-flags">Red flags that suggest something more</h2>
<p>ARFID is different in degree and in kind. The core difference is not stubbornness or taste preference — it is anxiety, sensory distress, or a genuine fear of eating. Look for these signs:</p>
<ul>
  <li><strong>Weight loss or failure to gain weight</strong> — the child is not getting enough nutrition to grow.</li>
  <li><strong>Dependence on supplements or tube feeding</strong> — the diet is so restricted the body cannot manage without medical support.</li>
  <li><strong>Fear of choking or vomiting</strong> — the child avoids foods not because of taste but because eating feels dangerous.</li>
  <li><strong>Sensory meltdowns at the table</strong> — not "I don't like it" but genuine distress at the texture, smell or appearance of food.</li>
  <li><strong>Extreme restriction</strong> — fewer than 10-15 foods, sometimes dropping entire categories (all vegetables, all proteins, all hot food).</li>
  <li><strong>No interest in food</strong> — the child forgets to eat, does not feel hunger, or treats eating as a chore to be endured.</li>
</ul>

<h2 id="uk-support">Where to get help in the UK</h2>
<p>If you recognise several of the red flags above, start with your GP. Ask for a referral to a paediatric dietitian or a CAMHS eating disorders service if available in your area. You do not need to wait for a crisis — early support makes a real difference.</p>
<p>Useful organisations: <strong>ARFID Awareness UK</strong> (arfidawarenessuk.org) has parent resources and practitioner directories. <strong>BEAT</strong> (beateatingdisorders.org.uk) runs a helpline for anyone affected by eating disorders. <strong>NICE guidelines NG69</strong> covers the recognition and treatment of eating disorders in children and young people — your GP should be familiar with it.</p>

<h2 id="what-not-to-do">What not to do while you wait</h2>
<p>If you suspect ARFID, traditional "fussy eating" strategies can backfire. Pressure, rewards, hiding food, and "try a bite" battles tend to increase anxiety. Keep mealtimes low-stakes. Protect the child's safe foods — those are keeping them fed while you get professional input. The condition is treatable, but it needs the right approach, and that starts with a proper assessment.</p>

